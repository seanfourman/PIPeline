export const DICTS = { he, en };
export type Lang = keyof typeof DICTS;

// Ready-made Israeli area names are stored in Hebrew. English readers see these.
export const AREA_NAMES_EN: Record<string, string> = {
  "שרון": "Sharon", "מרכז וגוש דן": "Center and Gush Dan", "צפון וחיפה": "North and Haifa", "מודיעין": "Modi'in", "ירושלים": "Jerusalem", "דרום": "South",
};

export function translate(lang: Lang, key: string, params: Record<string, string | number> = {}): any {
  let value: any = DICTS[lang];
  for (const part of key.split(".")) value = value?.[part];
  if (typeof value !== "string") return value ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}
